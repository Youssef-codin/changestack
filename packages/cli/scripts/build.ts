/**
 * Compile the CLI to one binary with the built viewer inside it, so `changestack` runs from
 * anywhere. Each viewer file is imported `with { type: "file" }`, which embeds it untouched;
 * the generated entry hands the server a map of URL path → embedded file, then starts the CLI.
 */
import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const cli = resolve(import.meta.dir, "..");
const viewer = resolve(cli, "../viewer/dist");

const walk = (dir: string): string[] =>
  readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

const files = walk(viewer);
if (!files.some((f) => f.endsWith("index.html"))) throw new Error(`no built viewer in ${viewer}; run the viewer build first`);

const out = join(cli, "dist");
mkdirSync(out, { recursive: true });
const entry = join(out, "entry.ts");
writeFileSync(
  entry,
  [
    "// Generated by scripts/build.ts. Do not edit.",
    ...files.map((f, i) => `import f${i} from ${JSON.stringify(f)} with { type: "file" };`),
    `(globalThis as { __CHANGESTACK_VIEWER__?: Record<string, string> }).__CHANGESTACK_VIEWER__ = {`,
    ...files.map((f, i) => `  ${JSON.stringify(`/${relative(viewer, f)}`)}: f${i},`),
    "};",
    `await import(${JSON.stringify(join(cli, "src/index.ts"))});`,
    "",
  ].join("\n"),
);

const result = await Bun.build({ entrypoints: [entry], compile: { outfile: join(out, "changestack") }, minify: false });
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
console.log(`changestack: built ${join(out, "changestack")} with ${files.length} viewer files`);
